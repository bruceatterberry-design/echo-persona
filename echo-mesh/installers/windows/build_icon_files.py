"""Makes EchoMesh.ico (the program's icon, several sizes) and ../../mesh/iconpng.py (a small embedded PNG for the tray and window title bars)
from icon.svg. Needs Google Chrome (to draw the SVG) and Pillow. Build-time only: the finished program does not need either."""
import base64, io, os, subprocess, sys, tempfile
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
SIZES = (16, 24, 32, 48, 64, 128, 256)


def render(svg, px, d):
    html = os.path.join(d, f"i{px}.html"); png = os.path.join(d, f"i{px}.png")
    sized = svg.replace("<svg ", '<svg width="%d" height="%d" ' % (px, px), 1)
    open(html, "w").write('<html><body style="margin:0;background:transparent">' + sized + "</body></html>")
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--default-background-color=00000000", f"--screenshot={png}",
                    f"--window-size={px},{px}", "file://" + html], check=True, capture_output=True)
    return Image.open(png).convert("RGBA")


def main():
    svg = open(os.path.join(HERE, "icon.svg")).read()
    with tempfile.TemporaryDirectory() as d:
        imgs = {px: render(svg, px, d) for px in SIZES}
    big = imgs[256]
    big.save(os.path.join(HERE, "EchoMesh.ico"), format="ICO", sizes=[(s, s) for s in SIZES], append_images=[imgs[s] for s in SIZES if s != 256])
    buf = io.BytesIO(); imgs[64].save(buf, "PNG", optimize=True)
    open(os.path.join(HERE, "..", "..", "mesh", "iconpng.py"), "w").write(
        '"""The Echo Mesh icon (64 px PNG) embedded so the tray and window title bars need no extra file. Generated by installers/windows/build_icon_files.py."""\nPNG_B64 = (\n'
        + "".join(f'    "{b}"\n' for b in [base64.b64encode(buf.getvalue()).decode()[i:i + 100] for i in range(0, len(base64.b64encode(buf.getvalue())), 100)]) + ")\n")
    print("wrote EchoMesh.ico and mesh/iconpng.py")


if __name__ == "__main__":
    main()
